import javax.swing.*; // Импортируем библиотеку Swing для создания GUI (кнопок, окон)
import java.awt.*; // Импортируем библиотеку AWT для работы с графикой (цвета, шрифты, отрисовка)

// Объявляем публичный класс NeonButton, который наследуется (extends) от стандартной кнопки JButton.
// Это значит, что наша кнопка будет иметь все свойства обычной кнопки, но мы добавим свои фишки.
public class NeonButton extends JButton {

    // Приватная переменная (доступна только внутри этого класса) типа Color.
    // В ней будет храниться цвет неонового свечения конкретной кнопки (красный,
    // синий, зеленый).
    private Color neonColor;

    // Конструктор класса. Вызывается при создании новой кнопки (например, new
    // NeonButton("ИГРАТЬ", Color.RED)).
    // Принимает текст (String text) и цвет (Color neonColor).
    public NeonButton(String text, Color neonColor) {
        super(text); // Вызываем конструктор родительского класса JButton, чтобы передать ему текст.
                     // Без этого текст не появится.

        this.neonColor = neonColor; // Сохраняем переданный цвет в нашу переменную класса, чтобы использовать его
                                    // при отрисовке.

        setContentAreaFilled(false); // Отключаем стандартную серую заливку фона кнопки Java. Нам нужна только наша
                                     // кастомная графика.
        setFocusPainted(false); // Убираем стандартную пунктирную рамку, которая появляется при нажатии (чтобы
                                // не портила вид).
        setBorderPainted(false); // Отключаем стандартную рамку кнопки (выпуклую или плоскую).
        setFont(new Font("Arial", Font.BOLD, 28)); // Устанавливаем шрифт: "Arial", жирный (BOLD), размер 28 пикселей.
        setForeground(Color.WHITE); // Устанавливаем цвет текста кнопки - белый.
        setCursor(new Cursor(Cursor.HAND_CURSOR)); // Меняем курсор мыши на "руку" при наведении на кнопку (как в
                                                   // браузере).
    }

    // Переопределяем (перезаписываем) метод paintComponent.
    // Этот метод отвечает за то, как кнопка выглядит на экране. Вызывается
    // автоматически каждый раз, когда кнопку нужно перерисовать.
    @Override
    protected void paintComponent(Graphics g) {
        // Создаем копию объекта Graphics и приводим его к Graphics2D.
        // Graphics2D - это продвинутая кисть, которая умеет рисовать сглаженные линии и
        // прозрачность.
        Graphics2D g2d = (Graphics2D) g.create();

        // Включаем сглаживание (Anti-aliasing). Без этого линии и круги на экране будут
        // "зубчатыми" (лесенкой).
        g2d.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);

        int w = getWidth(); // Получаем текущую ширину кнопки (например, 300 пикселей).
        int h = getHeight(); // Получаем текущую высоту кнопки (например, 80 пикселей).
        int arc = 30; // Задаем радиус закругления углов кнопки (чем больше число, тем круглее углы).

        // Устанавливаем цвет для фона кнопки: RGB (10, 10, 20) - почти черный, и 200 -
        // уровень прозрачности (от 0 до 255).
        g2d.setColor(new Color(10, 10, 20, 200));
        // Рисуем залитый прямоугольник с закругленными углами.
        // w - 1 и h - 1 делают его чуть меньше границ, чтобы рамка не обрезалась.
        g2d.fillRoundRect(0, 0, w - 1, h - 1, arc, arc);

        // Запускаем цикл 10 раз. Мы будем рисовать рамку 10 раз, накладывая её друг на
        // друга с разной прозрачностью.
        // Это и создаст эффект "объемного свечения" (Glow), как у неоновой лампы.
        for (int i = 0; i < 10; i++) {
            // Задаем цвет свечения: берем базовый цвет кнопки (например, красный) и ставим
            // прозрачность 15 (очень прозрачный).
            g2d.setColor(new Color(neonColor.getRed(), neonColor.getGreen(), neonColor.getBlue(), 15));
            // Задаем толщину линии. Каждый шаг цикла линия становится чуть тоньше (10 - i).
            g2d.setStroke(new BasicStroke(10 - i));
            // Рисуем контур (рамку) прямоугольника. С каждым шагом он смещается на
            // полпикселя внутрь (i/2).
            g2d.drawRoundRect(i / 2, i / 2, w - 1 - i, h - 1 - i, arc, arc);
        }

        // После создания свечения, рисуем четкую, яркую сердцевину рамки.
        g2d.setColor(neonColor); // Берем базовый цвет (например, чистый красный).
        g2d.setStroke(new BasicStroke(3)); // Делаем толщину линии 3 пикселя.
        g2d.drawRoundRect(2, 2, w - 5, h - 5, arc, arc); // Рисуем саму рамку поверх свечения.

        // Создаем объект FontMetrics. Он нужен, чтобы измерять ширину и высоту текста в
        // пикселях.
        // Это необходимо для того, чтобы текст стоял ровно по центру кнопки.
        FontMetrics fm = g2d.getFontMetrics();
        int textX = (w - fm.stringWidth(getText())) / 2; // Вычисляем X: (Ширина кнопки минус ширина текста) делить на
                                                         // 2.
        int textY = (h - fm.getHeight()) / 2 + fm.getAscent(); // Вычисляем Y: центрируем по высоте с учетом базовой
                                                               // линии шрифта.

        // Рисуем тень/свечение для текста. Делаем текст полупрозрачным цветом кнопки.
        g2d.setColor(new Color(neonColor.getRed(), neonColor.getGreen(), neonColor.getBlue(), 150));
        // Рисуем текст чуть смещенным вправо и вниз на 1 пиксель (создает эффект
        // объема).
        g2d.drawString(getText(), textX + 1, textY + 1);

        // Рисуем сам текст белым цветом поверх тени.
        g2d.setColor(Color.WHITE);
        g2d.drawString(getText(), textX, textY); // Выводим текст по вычисленным координатам.

        g2d.dispose(); // Освобождаем ресурсы Graphics2D, так как мы закончили рисовать. Это хорошая
                       // практика.
    }
} // Конец класса NeonButton
